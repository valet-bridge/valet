sub form_fixable
{
  my ($tname, $bbono) = @_;

  return 0 unless exists $FORM_CORRECTIONS{$tname};
  for my $ok (@{$FORM_CORRECTIONS{$tname}})
  {
    return 1 if $bbono eq $ok;
  }
  return 0;
}


sub form_number_fixable
{
  my ($bbono) = @_;
  return (exists $FORM_FLAT_LIST{$bbono} ? 1 : 0);
}


